_COUNTRIES = frozenset(COUNTRY_CODES)
_LANGUAGES = frozenset(LANGUAGE_CODES)
# UN/ECE Rec 20 ortak kodu: 2-3 büyük harf ya da rakam (KGM, C62, XCT).
UNECE_CODE_RE = re.compile(r"^[A-Z0-9]{2,3}$")


def normalize_country(value: str | None) -> str:
    return (value or "").strip().upper()


def is_country_code(value: str) -> bool:
    return value in _COUNTRIES


def normalize_language(value: str | None) -> str:
    return (value or "").strip().lower()


def is_language_code(value: str) -> bool:
    return value in _LANGUAGES


def is_unece_code(value: str) -> bool:
    return bool(UNECE_CODE_RE.match(value))
